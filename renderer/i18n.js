export function t(zh) {
  if (getLang() !== 'en') return zh;
  return DICT[zh] ?? zh;
}

/** 带占位替换：t('已选 {n} 篇', { n: 3 }) */
export function tf(zh, vars) {
  let s = t(zh);
  for (const [k, v] of Object.entries(vars || {})) s = s.replaceAll('{' + k + '}', String(v));
  return s;
}

/** 把 data-i18n 标注的静态元素批量切换到当前语言 */
export function applyI18n(root = document) {
  const en = getLang() === 'en';
  for (const el of root.querySelectorAll('[data-i18n]')) {
    const zh = el.getAttribute('data-i18n');
    el.textContent = en ? (DICT[zh] ?? zh) : zh;
  }
  for (const el of root.querySelectorAll('[data-i18n-title]')) {
    const zh = el.getAttribute('data-i18n-title');
    el.title = en ? (DICT[zh] ?? zh) : zh;
  }
  for (const el of root.querySelectorAll('[data-i18n-ph]')) {
    const zh = el.getAttribute('data-i18n-ph');
    el.placeholder = en ? (DICT[zh] ?? zh) : zh;
  }
  // <option> 需要保留 value：文案存在 data-i18n 上即可（同上）
  document.documentElement.lang = en ? 'en' : 'zh-CN';
}
